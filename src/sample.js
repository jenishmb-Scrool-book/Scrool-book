// Текст для того, у кого своей книги под рукой нет.
//
// Тестировщик закрытого теста ставит приложение по ссылке, а книги в .fb2 у
// него может не быть вовсе — и тогда всё, что он увидит за две недели, это
// инструкция про само приложение. Поэтому в библиотеке есть кнопка, которая
// кладёт короткий рассказ из трёх глав на языке интерфейса.
//
// Рассказ написан для приложения, а не взят из чужих книг, и это не случайно:
// всё, что лежит в пакете, Play считает содержимым приложения и спрашивает про
// него в анкете возрастного рейтинга. Своё нейтральное — и права чистые, и
// ответ «ограничений нет» правдивый. Роман с войной и казнями внутри пакета
// этот ответ сделал бы неверным, читают его или нет.
//
// Лежит отдельным куском сборки и грузится только по нажатию: незачем держать
// его в памяти у того, кто читает своё.
//
// Название здесь — то, под которым текст ляжет в библиотеку; по нему же
// кнопка понимает, что он уже там.
const SAMPLES = {
  ru: {title: 'Маяк на Тихом мысу', load: () => import('./books/sample-ru.txt?raw')},
  en: {title: 'The Lighthouse at Quiet Point', load: () => import('./books/sample-en.txt?raw')}
};

export const sampleOf = lang => SAMPLES[lang === 'en' ? 'en' : 'ru'];

/**
 * Текст: строка, а не модуль. Переводы строк — только LF: даже если файл
 * однажды выпишется с CRLF, в книгу не должно попасть ни одного CR.
 */
export const loadSample = lang => sampleOf(lang).load().then(m => m.default.replace(/\r\n?/g, '\n'));
