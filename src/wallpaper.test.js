import {statSync} from 'node:fs';
import {describe, it, expect} from 'vitest';
import {DEFAULT_WALL, THUMBS, WALLS} from './wallpaper.js';

// Обои — единственные картинки, которые названы не по номеру куска книги, а
// по списку, и единственные, которые лежат в сборке в двух размерах. Оба
// обстоятельства ломаются молча: неверный путь даёт не ошибку, а пустой чёрный
// домашний экран, а перепутанные размеры — решётку из двадцати полноразмерных
// снимков, то есть четверть гигабайта в памяти телефона.
//
// Поэтому проверка идёт по диску, а не по строкам: путь считается верным
// только тогда, когда по нему лежит файл.

const size = src => statSync(new URL('../public/' + src, import.meta.url)).size;

describe('готовые обои', () => {
  it('двадцать штук, и у каждых своя плитка', () => {
    expect(WALLS).toHaveLength(20);
    expect(THUMBS).toHaveLength(20);
    expect(new Set(WALLS).size).toBe(20);
  });

  it('каждый путь ведёт к файлу, который есть в сборке', () => {
    for (const src of [...WALLS, ...THUMBS]) expect(() => size(src)).not.toThrow();
  });

  it('обои крупнее своей плитки — иначе на экран уехала бы миниатюра', () => {
    for (let k = 0; k < WALLS.length; k++) expect(size(WALLS[k])).toBeGreaterThan(size(THUMBS[k]));
  });

  // Домашний экран и шаг первого запуска берут значение по умолчанию отсюда же.
  // Уйди оно из списка — вступление отмечало бы выбранной плитку, которой на
  // экране нет, а «Убрать свою» в настройках появлялось бы само собой.
  it('обои по умолчанию — одни из двадцати', () => {
    expect(WALLS).toContain(DEFAULT_WALL);
  });
});
