// Книга для того, у кого своей под рукой нет.
//
// Тестировщик закрытого теста ставит приложение по ссылке, а книги в .fb2 у
// него может не быть вовсе — и тогда всё, что он увидит за две недели, это
// инструкция про само приложение. Поэтому в библиотеке есть кнопка, которая
// кладёт настоящий роман: один, на языке интерфейса.
//
// Тексты — общественное достояние: «Капитанская дочка» по изданию 1960 года
// с Викитеки, «Алиса» по Project Gutenberg без их шапки и лицензии (она нужна,
// только пока текст раздаётся под их именем). Оба лежат в приложении и
// грузятся отдельным куском сборки — только когда нажали: полмегабайта
// текста незачем держать в памяти у того, кто читает своё.
//
// Название здесь — то, под которым книга ляжет в библиотеку; по нему же
// кнопка понимает, что книга уже там.
const BOOKS = {
  ru: {title: 'Капитанская дочка', load: () => import('./books/kapitanskaya.txt?raw')},
  en: {title: 'Alice’s Adventures in Wonderland', load: () => import('./books/alice.txt?raw')}
};

export const classicOf = lang => BOOKS[lang === 'en' ? 'en' : 'ru'];

/**
 * Текст книги: строка, а не модуль. Переводы строк — только LF: даже если
 * файл однажды выпишется с CRLF, в книгу не должно попасть ни одного CR.
 */
export const loadClassic = lang => classicOf(lang).load().then(m => m.default.replace(/\r\n?/g, '\n'));
