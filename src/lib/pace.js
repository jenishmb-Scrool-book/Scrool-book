// «Сколько осталось» в минутах.
//
// Процент прогресса отвечает на вопрос «далеко ли я», но не на «успею ли я
// сейчас». Человеку, который открыл телефон на пять минут в очереди, второе
// важнее — и это ровно тот сценарий, под который сделано приложение.

/**
 * Знаков в минуту. 1100 — спокойное чтение про себя на русском.
 *
 * Сверка с условной страницей из `pages.js`: 1800 знаков / 1100 ≈ 1,6 минуты
 * на страницу. Бумажная страница за полторы-две минуты — правдоподобно.
 *
 * Скорость фиксированная, а не измеренная по человеку: измерение требует
 * следить за временем на экране, а это и лишний код, и повод для приложения
 * знать о пользователе больше, чем ему нужно.
 */
export const CPM = 1100;

/** Целые минуты до конца текста. Непрочитанный хвост всегда ≥ 1 минуты. */
export function minutesLeft(offset, len) {
  const total = Math.max(0, Math.trunc(Number(len)) || 0);
  if (!total) return 0;
  const at = Math.min(Math.max(Math.trunc(Number(offset)) || 0, 0), total);
  const rest = total - at;
  if (!rest) return 0;
  return Math.max(1, Math.round(rest / CPM));
}

/** Минуты → часы и минуты, для строки вида «2 ч 5 мин». */
export function split(minutes) {
  const m = Math.max(0, Math.trunc(Number(minutes)) || 0);
  return {h: Math.floor(m / 60), m: m % 60};
}
