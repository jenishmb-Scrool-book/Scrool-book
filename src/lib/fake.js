// Бутафория для «мессенджеров»: витринные чаты в списке, время сообщений,
// счётчики непрочитанного.
//
// Всё детерминировано от индекса. Это не экономия на `Math.random()`, а
// требование: счётчик, меняющийся при каждом перерендере, читается не как
// живая переписка, а как баг. Так же сделаны лайки и просмотры в `ui/visual.js`.
//
// Имена намеренно НЕ переведены и не лежат в словаре. На настоящем телефоне
// контакты записаны на языке владельца, а не на языке интерфейса; «Мама» в
// английской локали выглядит достовернее, чем «Mom» у русскоязычного человека.

export const NAMES = ['Мама', 'Костя', 'Рабочий чат', 'Лена', 'Артём', 'Соседи', 'Даша', 'Паша'];

const DAY_START = 9 * 60;   // первое сообщение в 09:00
const SPAN = 13 * 60;       // и дальше в пределах дня, до 22:00
const STEP = 2;             // минуты между соседними сообщениями

const two = n => String(n).padStart(2, '0');

/**
 * Время сообщения по его номеру. Идёт вперёд с шагом в пару минут и
 * заворачивается обратно на 09:00 через ~390 сообщений.
 *
 * Заворот виден только тому, кто пролистает 390 пузырей вверх за один заход, —
 * окно рендера меньше полусотни. Настоящие даты потребовали бы разделителей
 * «Сегодня / Вчера» и привязки к календарю, а это декорация, а не данные.
 */
export function msgTime(i) {
  const n = Math.max(0, Math.trunc(Number(i)) || 0);
  const t = DAY_START + (n * STEP) % SPAN;
  return two(Math.floor(t / 60)) + ':' + two(t % 60);
}

// Счётчик непрочитанного у витринного чата. Ноль у большинства: список, где
// всё подсвечено, выглядит как свалка, а не как телефон.
export function unread(i) {
  const n = Math.max(0, Math.trunc(Number(i)) || 0);
  return n % 3 === 1 ? (n * 7) % 9 + 1 : 0;
}

/**
 * Витринные чаты для списка. Настоящий чат в приложении один — с книгой;
 * эти нужны, чтобы экран читался как мессенджер, а не как список из одной строки.
 *
 * `stub` — номер заготовленной реплики (0..2), текст берётся из словаря по
 * ключу `chats.stub_N`: здесь язык интерфейса неизвестен и знать его незачем.
 * `seed` — число для градиента аватарки, чтобы `lib/` не тянул `ui/visual.js`.
 */
export function contacts(n = 5) {
  const count = Math.max(0, Math.trunc(Number(n)) || 0);
  const out = [];
  for (let i = 0; i < count; i++) {
    out.push({
      id: 'c' + i,
      name: NAMES[i % NAMES.length],
      seed: i * 13 + 5,
      stub: i % 3,
      time: msgTime(i * 37),
      unread: unread(i)
    });
  }
  return out;
}
