// Размер картинки в точках — прочитанный из заголовка файла, без декодирования.
//
// Нужен ради одной вещи: рамка под иллюстрацию должна знать свою высоту ДО
// того, как картинка доехала. Раньше высота была записана в стилях числом, и
// любая картинка — что марка на полстраницы, что разворот — показывалась
// полоской в 210 точек: портрет сжимался до спичечного коробка, а по бокам
// оставались поля. Зная настоящие пропорции, рамка встаёт точно по картинке,
// и лента не дёргается, когда та наконец загрузилась.
//
// Декодировать ради этого нечего: ширина и высота лежат в первых байтах файла
// у всех форматов, которые мы вообще берём (см. белый список в img.js).

/** Ширина и высота в заголовке PNG: IHDR идёт первым чанком, всегда. */
const png = (u8, dv) =>
  u8[0] === 0x89 && u8[1] === 0x50 && u8[2] === 0x4e && u8[3] === 0x47 && u8.length >= 24
    ? {w: dv.getUint32(16), h: dv.getUint32(20)}
    : null;

/** GIF: логический экран сразу за подписью «GIF87a»/«GIF89a», порядок младшим вперёд. */
const gif = (u8, dv) =>
  u8[0] === 0x47 && u8[1] === 0x49 && u8[2] === 0x46 && u8.length >= 10
    ? {w: dv.getUint16(6, true), h: dv.getUint16(8, true)}
    : null;

/** BMP: в заголовке высота бывает отрицательной — это значит «строки сверху вниз». */
const bmp = (u8, dv) =>
  u8[0] === 0x42 && u8[1] === 0x4d && u8.length >= 26
    ? {w: Math.abs(dv.getInt32(18, true)), h: Math.abs(dv.getInt32(22, true))}
    : null;

/**
 * WebP. Форматов внутри три, и размер в каждом лежит по-своему:
 * `VP8 ` — сжатие с потерями, `VP8L` — без потерь, `VP8X` — расширенный
 * (анимация, прозрачность), где размер холста записан тремя байтами минус один.
 */
function webp(u8, dv) {
  const tag = i => String.fromCharCode(u8[i], u8[i + 1], u8[i + 2], u8[i + 3]);
  if (u8.length < 20 || tag(0) !== 'RIFF' || tag(8) !== 'WEBP') return null;
  const kind = tag(12);
  if (kind === 'VP8 ' && u8.length >= 30) {
    // Перед размером стоит трёхбайтовый тег кадра и синхрокод 9d 01 2a.
    if (u8[23] !== 0x9d || u8[24] !== 0x01 || u8[25] !== 0x2a) return null;
    return {w: dv.getUint16(26, true) & 0x3fff, h: dv.getUint16(28, true) & 0x3fff};
  }
  if (kind === 'VP8L' && u8.length >= 25) {
    if (u8[20] !== 0x2f) return null;
    const bits = u8[21] | (u8[22] << 8) | (u8[23] << 16) | (u8[24] << 24);
    return {w: (bits & 0x3fff) + 1, h: ((bits >>> 14) & 0x3fff) + 1};
  }
  if (kind === 'VP8X' && u8.length >= 30)
    return {
      w: (u8[24] | (u8[25] << 8) | (u8[26] << 16)) + 1,
      h: (u8[27] | (u8[28] << 8) | (u8[29] << 16)) + 1
    };
  return null;
}

// Маркеры JPEG, за которыми идёт описание кадра с его размерами. Из диапазона
// C0..CF выпадают три: C4 — таблицы Хаффмана, C8 — зарезервирован, CC — таблица
// арифметического кодирования. Их длина считается так же, а размеров в них нет.
const SOF = m => m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc;

/**
 * JPEG. Размер здесь не в начале файла: до него лежат превью, цветовые профили
 * и EXIF, поэтому сегменты приходится перебирать по длинам.
 */
function jpeg(u8) {
  if (u8[0] !== 0xff || u8[1] !== 0xd8) return null;
  let i = 2;
  while (i + 9 < u8.length) {
    if (u8[i] !== 0xff) return null;          // не на границе сегмента — дальше гадать нечего
    const m = u8[i + 1];
    // Заполнитель FF и односложные маркеры длины не несут: шагаем на два байта.
    if (m === 0xff) {i += 1; continue;}
    if (m === 0x01 || (m >= 0xd0 && m <= 0xd9)) {i += 2; continue;}
    if (SOF(m)) return {h: (u8[i + 5] << 8) | u8[i + 6], w: (u8[i + 7] << 8) | u8[i + 8]};
    const len = (u8[i + 2] << 8) | u8[i + 3];
    if (len < 2) return null;                 // битая длина: шаг вперёд был бы бесконечным
    i += 2 + len;
  }
  return null;
}

/**
 * Размер картинки по её первым байтам.
 *
 * @param {Uint8Array} bytes начало файла; для JPEG хватает нескольких десятков
 *   килобайт, остальным форматам — трёх десятков байт
 * @returns {{w: number, h: number}|null} null — формат не узнан или заголовок
 *   оборван: рамка тогда возьмёт запасные пропорции
 */
export function pixels(bytes) {
  if (!bytes || bytes.length < 10) return null;
  const u8 = bytes;
  const dv = new DataView(u8.buffer, u8.byteOffset, u8.byteLength);
  const r = png(u8, dv) || jpeg(u8) || gif(u8, dv) || webp(u8, dv) || bmp(u8, dv);
  // Нулевая сторона — это не размер, а мусор на месте заголовка. Потолок в
  // 65535 стоит там же, где он стоит у самих форматов: больше — значит,
  // прочитано не то поле.
  return r && r.w > 0 && r.h > 0 && r.w <= 0xffff && r.h <= 0xffff ? r : null;
}
