// Чанкер: режет книгу на карточки один раз при импорте.
// Чистая функция без побочных эффектов — от неё зависит нумерация курсора,
// поэтому один и тот же текст обязан всегда давать один и тот же массив.

/**
 * @param {string} text исходный текст книги
 * @param {number} [max=280] желаемый потолок длины куска в символах
 * @returns {string[]} куски без пустых
 */
export function chunk(text, max = 280) {
  const out = [];
  // Абзац — то, что между пустыми строками. Внутри абзаца пробелы схлопываем:
  // в .txt перенос строки стоит по ширине колонки, а не по смыслу.
  for (const para of String(text ?? '').split(/\n\s*\n+/)) {
    const p = para.trim().replace(/\s+/g, ' ');
    if (!p) continue;
    if (p.length <= max) { out.push(p); continue; }

    // Абзац длинный — добираем предложениями, пока влезает.
    let buf = '';
    for (const s of p.split(/(?<=[.!?…»"])\s+/)) {
      if (buf && (buf + ' ' + s).length > max) { out.push(buf); buf = s; }
      else buf = buf ? buf + ' ' + s : s;
    }
    // Одно предложение длиннее max резать не по чему: buf на первом шаге станет
    // этим предложением и выйдет отдельным куском. Он длиннее max — и это лучше,
    // чем рубить слово посередине или, хуже того, крутиться в цикле.
    if (buf) out.push(buf);
  }
  return out;
}
