// Сколько прочитано сегодня и сколько дней подряд.
//
// Хранятся три числа, а не история по дням: дата последнего дня с чтением,
// сколько знаков прочитано в тот день и сколько дней подряд к нему привело.
// Больше ответа на «читал ли я сегодня и не бросил ли» здесь ничего нет — и
// знать о человеке больше приложению незачем (то же правило, по которому
// скорость чтения в `pace.js` не измеряется, а зафиксирована).
//
// Прочитанным считается то же, что везде: сдвиг курсора вперёд. Прыжок из
// оглавления и поиска — это переход, а не чтение, и в счёт не идёт (см.
// `setOffset` в сторе). Порог «засчитан ли день» — ноль: в какой-то день
// читается только по три строки, и первая книга прямо говорит, что это тоже
// чтение. Серия, которая требует норму, наказывает ровно за такой день.

import {CPM} from './pace.js';

/**
 * Больше этого один сдвиг курсора не засчитывает. Бросок ленты пальцем
 * проносит десятки карточек за секунду; это не чтение, и две страницы — с
 * запасом больше, чем помещается на экране любого из «приложений».
 */
export const STEP = 3600;

/**
 * Потолок скорости, знаков в миллисекунду: втрое быстрее спокойного чтения
 * из `pace.js`. Быстрее этого глаза не читают, а листают — и сдвиг, который
 * пронёс курсор быстрее, засчитывается не целиком, а сколько можно было успеть
 * прочитать с прошлого сдвига. Без этого десять бросков ленты за двадцать
 * секунд давали «Сегодня 33 мин».
 */
export const FAST = (3 * CPM) / 60000;

/**
 * Сколько из сдвига на `chars` знаков засчитать, если с прошлого сдвига прошло
 * `ms` миллисекунд. Время живёт в памяти, в хранилище его нет.
 */
export function credit(chars, ms) {
  const c = Math.trunc(Number(chars)) || 0;
  const t = Math.max(0, Number(ms) || 0);
  return Math.max(0, Math.min(c, STEP, Math.floor(t * FAST)));
}

const pad = n => String(n).padStart(2, '0');

/** «2026-09-26» по МЕСТНОМУ времени: день кончается в полночь у человека, а не в Гринвиче. */
export const dayKey = d => d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate());

const DAY = /^(\d{4})-(\d{2})-(\d{2})$/;

/** Ключ предыдущего дня. Через конструктор даты: он сам знает длину месяцев и переводы часов. */
function before(key) {
  const [, y, m, d] = DAY.exec(key);
  return dayKey(new Date(Number(y), Number(m) - 1, Number(d) - 1, 12));
}

/** Запись из хранилища. Всё, что не похоже на целую запись, — null. */
export function readPace(raw) {
  if (!raw || typeof raw !== 'object' || typeof raw.d !== 'string' || !DAY.test(raw.d)) return null;
  const n = Math.trunc(Number(raw.n));
  const s = Math.trunc(Number(raw.s));
  if (!Number.isFinite(n) || n < 0 || !Number.isFinite(s) || s < 1) return null;
  return {d: raw.d, n, s};
}

/**
 * Засчитать `chars` прочитанных знаков. Отдаёт НОВУЮ запись, а если считать
 * нечего — ту же самую: стор по этому решает, писать ли мету.
 */
export function tally(p, chars, now = new Date()) {
  const add = Math.min(STEP, Math.trunc(Number(chars)) || 0);
  if (add <= 0) return p;
  const today = dayKey(now);
  if (!p) return {d: today, n: add, s: 1};
  if (p.d === today) return {d: today, n: p.n + add, s: p.s};
  // Последний день «в будущем» — часы перевели назад. Это не новый день и не
  // обрыв: серию оставляем, а день начинаем заново.
  if (p.d > today) return {d: today, n: add, s: p.s};
  if (p.d === before(today)) return {d: today, n: add, s: p.s + 1};
  return {d: today, n: add, s: 1};
}

/** Знаков прочитано сегодня. */
export const todayOf = (p, now = new Date()) => (p && p.d === dayKey(now) ? p.n : 0);

/**
 * Дней подряд. Серия жива и тогда, когда сегодня ещё не читали: день не
 * кончился, и показывать «серия прервана» в девять утра было бы неправдой.
 */
export function streakOf(p, now = new Date()) {
  if (!p) return 0;
  const today = dayKey(now);
  return p.d === today || p.d === before(today) ? p.s : 0;
}
