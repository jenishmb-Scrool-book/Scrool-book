import {useT} from '../i18n.js';
import Glyph from './Glyph.jsx';

/**
 * «Вернуться к месту» — кнопка, которая появляется, только когда человек
 * пролистал назад.
 *
 * Она — вторая половина решения «листать назад можно, а место сохраняется».
 * Курсор при листании вверх не двигается, поэтому место цело; но без обратной
 * дороги это ловушка: чтобы вернуться, пришлось бы вручную пролистать те же
 * тридцать карточек. Ровно та же кнопка стоит в любом мессенджере, когда
 * уходишь вверх по переписке, — и означает ровно то же самое.
 *
 * Стрелка всегда вниз, и это не упрощение: обогнать курсор прокруткой нельзя —
 * вперёд он едет вместе с ней. Значит место всегда ниже видимого.
 */
export default function Resume({away, onClick}) {
  const t = useT();
  if (!away) return null;
  return (
    <button className="resume" onClick={onClick}>
      <Glyph name="next" />
      {t('reader.resume')}
    </button>
  );
}
