// Размер фрагмента для каждого экрана.
//
// Это главный рычаг различия между «приложениями»: один и тот же текст в
// «коротком» читается рваными репликами, а в «видео» — длинными абзацами.
// Разный темп ощущается как разные приложения гораздо сильнее, чем разная палитра.
//
// Позиция чтения при этом общая — стор хранит смещение в символах, а не номер
// фрагмента, поэтому переключение между экранами не сдвигает место в книге.
export const SIZE = {
  roster: 90,    // строка списка чатов — строка и есть кусок книги
  vlist: 140,    /* название ролика: длиннее строки чата, потому что под каждым
                    названием стоит превью 16:9 — на экран помещается два-три
                    ролика, и коротким куском чтение по списку встало бы */
  tweets: 180,
  chats: 200,
  comment: 200,  // комментарий под роликом
  stories: 220,
  feed: 250,
  reels: 280,
  video: 600     // описание ролика — длинный кусок, читается как страница
};

// Про «видео». Описание на 600 плюс шесть комментариев по 200 — это ровно
// 1800 знаков, условная страница из `lib/pages.js`. Один открытый ролик
// получается одной страницей книги: описание — её начало, комментарии —
// продолжение, «следующее видео» — следующая страница.
