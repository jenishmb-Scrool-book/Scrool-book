// Размер фрагмента для каждого экрана.
//
// Это главный рычаг различия между «приложениями»: один и тот же текст в
// «коротком» читается рваными репликами, а в «видео» — длинными абзацами.
// Разный темп ощущается как разные приложения гораздо сильнее, чем разная палитра.
//
// Позиция чтения при этом общая — стор хранит смещение в символах, а не номер
// фрагмента, поэтому переключение между экранами не сдвигает место в книге.
export const SIZE = {
  roster: 90,    // строка списка чатов — строка и есть кусок книги
  vlist: 140,    /* название ролика: длиннее строки чата, потому что под каждым
                    названием стоит превью 16:9 — на экран помещается два-три
                    ролика, и коротким куском чтение по списку встало бы */
  tweets: 180,
  chats: 200,
  comment: 200,  // комментарий под роликом
  stories: 220,
  feed: 250,
  reels: 280,
  video: 600     // описание ролика — длинный кусок, читается как страница
};

// Про «видео». Описание на 600 плюс шесть комментариев по 200 — это ровно
// 1800 знаков, условная страница из `lib/pages.js`. Один открытый ролик
// получается одной страницей книги: описание — её начало, комментарии —
// продолжение, «следующее видео» — следующая страница.

// Кегль приложения в пикселях — три градации из styles.css (`--fs`).
const FS = {sm: 14, md: 16, lg: 19};

/**
 * Кусок клипа, который помещается на экран целиком.
 *
 * Клип — единственный экран, где кусок обязан влезть: карточка ровно в
 * экран, листается она со snap'ом, и хвост текста уходил во внутреннюю
 * прокрутку, которую не видно, — свайп уносил к следующему клипу, а конец
 * куска никто не прочитывал. На 360×640 с крупным кеглем так было с каждым
 * вторым клипом: в карточку влезает около двухсот знаков, а кусок — 280.
 *
 * Считаем по той же вёрстке, что в styles.css (`.reel`, `.reel .txt`):
 * ширина текста — экран минус поля 20 + 74, высота — 76 % карточки, кегль
 * 1,31 от базового, строка 1,45, средняя буква жирной кириллицы — около 0,56
 * кегля. Запас 20 % — на перенос слов. Место чтения в символах, поэтому
 * другая нарезка его не сдвигает.
 *
 * @returns {number} от 120 до SIZE.reels
 */
export function reelSize(font, width, height) {
  const px = (FS[font] || FS.md) * 1.31;
  const w = Math.min(Number(width) || 375, 440) - 94;
  const h = (Number(height) || 812) - 57;              // минус нижняя панель
  const lines = Math.floor((h * 0.76) / (px * 1.45));
  const perLine = Math.floor(w / (px * 0.56));
  const fit = Math.floor(lines * perLine * 0.8);
  return Math.max(120, Math.min(SIZE.reels, fit));
}

