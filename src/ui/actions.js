// Куда ведёт кнопка. Одна таблица на все «приложения».
//
// Раньше нижние панели, чипсы фильтров и половина значков в шапках были
// нарисованными: «нерабочие намеренно». Владелец на это и указал — кнопка,
// которая не нажимается, ломает обман вернее, чем кривой цвет: настоящее
// приложение так себя не ведёт нигде.
//
// Правило, по которому у каждой кнопки нашлось назначение, ровно одно:
// **кнопка ведёт туда, куда ведёт её значок в настоящем приложении, — если у
// нас есть чем ответить.**
//
//   поиск                           → поиск по книге: оглавление, открытое
//                                     сразу на своей вкладке поиска. Лупа,
//                                     которая открывает список глав, — это
//                                     надпись «поиск» над чем-то другим.
//   подписки, фильтры, «⋮»          → оглавление. В оригинале это «выбрать,
//                                     что смотреть»; у нас выбирают главу.
//   «＋» (создать)                   → библиотека. Создать здесь можно ровно
//                                     одно — добавить книгу.
//   профиль, «Вы», «Я»              → настройки. Это и есть свой раздел.
//   раздел, у которого есть свой
//   движок (клипы, истории, чаты)   → этот движок. Курсор общий, поэтому
//                                     переход продолжает то же место книги.
//   «Главная» на своей же вкладке   → к месту чтения. В настоящих панелях тап
//                                     по активной вкладке ведёт к началу ленты,
//                                     то есть к самому свежему; у нас самое
//                                     «свежее» — место, где читаешь. Верх
//                                     списка здесь — начало окна рендера, то
//                                     есть случайный кусок книги позади места,
//                                     и туда «Главная» раньше и уносила.
//
// Чему честного ответа не нашлось — того на экране больше нет. «Поделиться» и
// «Сохранить» под роликом убраны: кнопка, которая ничего не сохраняет, это та
// же мёртвая кнопка, только с подписью.

/** Действия, которые обрабатывает не переход, а сам экран. */
export const LOCAL = ['top', 'here'];

/**
 * Действие, начинающееся с этого, — вкладка внутри экрана: её разбирает сам
 * экран, до `run` такие не доходят.
 */
export const TAB = 'tab:';

/**
 * Переходы с параметром: имя действия → [экран, параметр]. Таблица кнопок
 * хранит строку, а не объект, — так её проверяет один тест на всё
 * приложение (`tabs.test.js`); параметр достраивается здесь.
 */
export const ALIAS = {find: ['toc', 'search']};

/**
 * Подпись кнопки для чтения с экрана — по назначению, а не по значку.
 *
 * Значок без подписи TalkBack читает словом «кнопка», и только. Подпись по
 * назначению, а не по рисунку: «самолётик» или «сетка» не говорят, что будет
 * по нажатию, а «Оглавление» — говорит. Таблица одна, как и таблица действий, и
 * `tabs.test.js` требует подпись у каждой кнопки без видимой надписи.
 */
export const LABEL = {
  top: 'a11y.top',
  here: 'a11y.here',
  find: 'toc.tab_search',
  toc: 'toc.title',
  library: 'a11y.add',
  settings: 'set.title',
  chats: 'a11y.chats',
  chat: 'a11y.chats',
  stories: 'a11y.stories',
  reels: 'a11y.reels',
  video: 'a11y.video'
};

/** Ключ подписи для действия. Вкладка `tab:x` подписывается словом вкладки. */
export const labelOf = action =>
  LABEL[action] || (action && action.startsWith(TAB) ? 'chats.tab_' + action.slice(TAB.length) : '');

/**
 * Выполнить действие кнопки.
 *
 * @param {string} action  из таблицы выше: 'toc', 'library', 'reels', 'top'…
 *                         Префикс `tab:` — вкладка внутри экрана, её разбирает
 *                         сам экран, сюда такие не доходят.
 * @param {object} ctx
 * @param {(id: string, opt?: object) => void} ctx.go переход между экранами
 * @param {{current: HTMLElement|null}} [ctx.boxRef] прокручиваемое тело экрана
 * @param {number} [ctx.pos] текущий фрагмент — для 'here'
 */
export function run(action, {go, boxRef, pos}) {
  // Прокручиваемое тело экрана. Ref, если он под рукой у вызывающего, иначе
  // ищем сами: на экране оно всегда одно и всегда `.body` внутри `.screen`.
  // Тащить ref через три компонента ради двух действий дороже, чем один
  // запрос к DOM, который к тому же не может отстать от перерисовки.
  const box = (boxRef && boxRef.current) || document.querySelector('.screen .body');
  // «top» — к месту чтения, если экран его знает; иначе (журнал звонков,
  // список людей — там книги нет) — к верху списка.
  if (action === 'top') {
    const el = box && pos != null && box.querySelector('[data-i="' + pos + '"]');
    if (box) box.scrollTo({top: el ? Math.max(0, el.offsetTop - 8) : 0, behavior: 'smooth'});
    return;
  }
  if (action === 'here') {
    // К месту, где читаешь. Ищем карточку по data-i — тот же признак, по
    // которому её находит окно рендера, так что селектор знать не нужно.
    const el = box && box.querySelector('[data-i="' + pos + '"]');
    if (box && el) box.scrollTo({top: Math.max(0, el.offsetTop - 8), behavior: 'smooth'});
    return;
  }
  // hasOwnProperty, а не Object.hasOwn: тот есть только с 93-й версии WebView.
  if (Object.prototype.hasOwnProperty.call(ALIAS, action)) {
    const [id, arg] = ALIAS[action];
    go(id, {arg});
    return;
  }
  if (action) go(action);
}
