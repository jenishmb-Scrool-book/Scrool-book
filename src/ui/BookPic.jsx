import {useEffect, useState} from 'react';
import {useStore} from '../store.jsx';
import {useT} from '../i18n.js';
import {useOpenPic} from './PicView.jsx';

// Картинка из книги — на карточке, которой досталось её смещение.
//
// Это не снимок из `ui/pics.js`: тот подложен под текст для вида и лежит в
// сборке, а этот пришёл из файла, который принёс человек. Отсюда и разница в
// обращении. Снимок известен сразу, картинка книги — нет: она лежит отдельной
// записью в хранилище и читается тогда, когда до неё долистали. Читать их все
// при открытии книги нельзя — иллюстрированный epub это десятки мегабайт.
//
// Поэтому у рамки есть высота ДО того, как картинка доехала. Иначе появление
// картинки раздвигало бы список под пальцем, а вместе с ним уезжало бы и
// место, на котором человек читает: за прокруткой следит курсор.

/**
 * Одна картинка. Пока грузится — пустая рамка своей высоты; если файла не
 * нашлось (хранилище почистили, запись побилась) — не рисуем ничего: пустая
 * рамка навсегда хуже, чем её отсутствие.
 */
function One({pic, cls}) {
  const {getPic} = useStore();
  const openPic = useOpenPic();
  const t = useT();
  const [src, setSrc] = useState(null);           // null — ещё грузим, '' — нечего показывать

  useEffect(() => {
    let live = true;
    setSrc(null);
    Promise.resolve(getPic(pic.k))
      .then(v => {
        if (live) setSrc(v || '');
      })
      .catch(() => {
        if (live) setSrc('');
      });
    return () => {live = false;};
  }, [getPic, pic.k]);

  if (src === '') return null;

  // Пропорции рамки — пропорции самой картинки: её размер стор прочитал из
  // заголовка файла ещё при импорте. Отсюда две вещи сразу: высота известна до
  // загрузки, и картинка стоит во всю ширину карточки, а не полоской посреди
  // полей. У книг, добавленных раньше, размера нет — там останутся запасные
  // пропорции из стилей.
  const ar = pic.w > 0 && pic.h > 0 ? {'--arw': pic.w, '--arh': pic.h} : undefined;

  // Во весь экран открывается только картинка в собственной рамке. Превью
  // ролика и квадратик в списке переписок живут в чужой: там нажатие открывает
  // сам ролик и сам разговор, и перехватывать его нельзя.
  const big = !cls && src ? () => openPic(src) : undefined;

  return (
    <figure className={cls ? 'bpic ' + cls : 'bpic'} style={ar}
            onClick={big} role={big ? 'button' : undefined}
            aria-label={big ? t('pic.open') : undefined}>
      {/* Только `<img src=...>`: содержимое книги в разметку не попадает
          никогда, ни здесь, ни где-либо ещё. Сам `src` собран из белого
          списка типов в lib/img.js, а не из строки, взятой в файле. */}
      {src ? <img src={src} alt={t('pic.alt')} /> : null}
    </figure>
  );
}

/**
 * Картинки одной карточки. Ничего не рисует, если их нет, — а нет их у
 * подавляющего большинства карточек, поэтому вызывать можно везде.
 *
 * @param {{list: Array<{at:number,k:number}>, cls?: string, one?: boolean}} props
 *   `cls` — вид рамки: `fill` (влезть в чужую, как превью ролика) или `thumb`
 *   (квадратик в строке списка). `one` — показать только первую: в чужую рамку
 *   и в строку списка вторая не поместится, а наложенные друг на друга
 *   картинки — это не «две картинки», это одна испорченная.
 */
export default function BookPics({list, cls, one}) {
  if (!list || !list.length) return null;
  const items = one ? list.slice(0, 1) : list;
  return items.map(p => <One key={p.k + ':' + p.at} pic={p} cls={cls} />);
}
