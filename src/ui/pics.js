// Картинки для наполнения лент.
//
// Лежат в `public/pics` и попадают в сборку. Не тянутся по сети намеренно: у
// приложения нет разрешения INTERNET, и появиться оно не должно ради фона.
// Откуда взяты и по какой лицензии — в `tools/fetch-pics.py`.
//
// Четыре ленты, потому что четыре формы кадра. Одна картинка 4:5 на все случаи
// не годится: в клипах и историях кадр вертикальный во весь экран, у обложек
// видео он широкий, а аватарка круглая. Растянутый не в своё соотношение
// снимок обрезается по центру, и от него остаётся середина без сюжета.
//
// Привязка к номеру куска, а не к случайности: один и тот же кусок книги
// всегда показывается на одной и той же картинке. Картинка, меняющаяся при
// перерисовке, читается как мигание, а не как лента.

/** Сколько снимков в каждой ленте. Числа выдаёт `tools/fetch-pics.py --build`. */
export const POOLS = {post: 390, wide: 195, tall: 195, face: 190};

/**
 * Путь к картинке.
 * @param {'post'|'wide'|'tall'|'face'} kind лента
 * @param {number} i номер куска; отрицательные и мусор не роняют
 */
export function pic(kind, i) {
  const count = POOLS[kind] || POOLS.post;
  // Проверка на конечность, а не просто `|| 0`: Infinity истинно, и остаток
  // от деления бесконечности даёт NaN — путь `pics/post/NaN.webp` и пустой кадр.
  const raw = Math.trunc(Number(i));
  const n = Number.isFinite(raw) ? raw : 0;
  const k = ((n % count) + count) % count;
  return 'pics/' + (POOLS[kind] ? kind : 'post') + '/' + String(k + 1).padStart(3, '0') + '.webp';
}

/** Готовый `background` со снимком поверх заливки — на случай, если файл не открылся. */
export const shot = (kind, i, fallback) =>
  `url(${pic(kind, i)}) center/cover no-repeat` + (fallback ? ',' + fallback : '');

// Своё лицо аккаунта: оно одно на всё приложение и меняться не должно — это
// лицо автора ленты, а не иллюстрация к куску.
export const FACE = 7;
