// Картинки для наполнения лент.
//
// Сто снимков лежат в `public/pics` и попадают в сборку. Не тянутся по сети
// намеренно: у приложения нет разрешения INTERNET, и появиться оно не должно
// ради фона. Откуда взяты и по какой лицензии — в `tools/fetch-pics.py`.
//
// Привязка к индексу, а не к случайности: один и тот же кусок книги всегда
// показывается на одной и той же картинке. Картинка, меняющаяся при
// перерисовке, читается как мигание, а не как лента.

export const COUNT = 100;

/** Путь к картинке для куска `i`. Отрицательные и мусор не роняют. */
export function pic(i) {
  const n = Math.trunc(Number(i)) || 0;
  const k = ((n % COUNT) + COUNT) % COUNT;
  return 'pics/' + String(k + 1).padStart(3, '0') + '.webp';
}

/** Готовый `background` со снимком поверх градиента — на случай, если файл не открылся. */
export const shot = (i, fallback) =>
  `url(${pic(i)}) center/cover no-repeat` + (fallback ? ',' + fallback : '');

