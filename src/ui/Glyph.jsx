/** Есть ли такой значок. Нужен тестам: имя с опечаткой иначе рисует пустоту. */
export const has = name => Object.hasOwn(GLYPHS, name);

/**
 * @param {string} name имя из GLYPHS
 * @param {string} [title] подпись для чтения с экрана; без неё значок скрыт от него
 */
export default function Glyph({name, title}) {
  const g = GLYPHS[name];
  if (!g) return null;
  return (
    <svg className="gl" viewBox="0 0 24 24" aria-hidden={title ? undefined : 'true'}
         role={title ? 'img' : undefined}>
      {title ? <title>{title}</title> : null}
      {g}
    </svg>
  );
}
