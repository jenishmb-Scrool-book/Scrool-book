// Разбор цвета, замеренного с экрана.
//
// Заведено ради одной вещи: статус-бар должен принимать цвет той шапки, под
// которой он стоит. Цвет берётся не из таблицы, а из `getComputedStyle` —
// таблица разошлась бы с палитрой на первой же правке скина, и разошлась бы
// молча. Значит, нужен разбор строки вида `rgb(50, 130, 184)`.

const RGB = /rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:[,/\s]+([\d.]+))?/i;
const HEX = /^\s*#([0-9a-f]{3}|[0-9a-f]{6})\s*$/i;

/**
 * Строка из getComputedStyle → [r, g, b].
 *
 * Полупрозрачное считаем отсутствием цвета: у элемента с градиентом
 * `background-color` пустой, и покрасить бар в него значило бы получить
 * чёрную полоску там, где на экране красивый переход.
 *
 * Понимает и `#rrggbb`: полноэкранные экраны (клипы, истории, плеер) цвет не
 * замеряют, а объявляют — там под баром лежит не фон элемента, а картинка.
 *
 * @param {string} css
 * @returns {number[]|null}
 */
export function rgbOf(css) {
  const h = HEX.exec(String(css || ''));
  if (h) {
    const v = h[1].length === 3 ? h[1].replace(/./g, c => c + c) : h[1];
    return [0, 2, 4].map(i => parseInt(v.slice(i, i + 2), 16));
  }
  const m = RGB.exec(String(css || ''));
  if (!m) return null;
  if (m[4] !== undefined && Number(m[4]) < 0.9) return null;
  return [m[1], m[2], m[3]].map(v => Math.max(0, Math.min(255, Math.round(Number(v)))));
}

/** [r, g, b] → '#rrggbb'. Нативному плагину нужен именно такой формат. */
export const hexOf = rgb => '#' + rgb.map(v => v.toString(16).padStart(2, '0')).join('');

/**
 * Светлая ли подложка. По ней выбирается, чёрные значки на баре или белые:
 * коэффициенты — воспринимаемая яркость, зелёный человек видит ярче синего.
 */
export const isLight = ([r, g, b]) => (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255 > 0.55;
