import {useT} from '../i18n.js';

// Нижняя панель навигации. Ни одно настоящее приложение без неё не выглядит
// настоящим — и это самая дешёвая узнаваемость из всех: четыре значка внизу.
//
// Нерабочая намеренно — как вкладки в клипах и чипсы фильтров: вести ей некуда,
// раздел в «приложении» ровно один. Выход при этом есть на каждом экране
// отдельно («‹» в шапке, на полноэкранных — поверх карточки), так что панель
// ничего не отбирает.
//
// Подпись под значком необязательна: в «ленте» её нет и в оригинале, а
// панель с лишними словами читается как чужая.
//
// @param {Array<[string,string?]>} items пары [значок, ключ подписи]
// @param {number} active индекс активного значка
export default function Tabbar({items, active = 0}) {
  const t = useT();
  return (
    <div className="tabbar" aria-hidden="true">
      {items.map(([glyph, key], k) => (
        <span key={k} className={k === active ? 'on' : ''}>
          <b>{glyph}</b>
          {key ? <i>{t(key)}</i> : null}
        </span>
      ))}
    </div>
  );
}
