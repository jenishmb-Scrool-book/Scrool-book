// Фон карточки выводится из её индекса — один и тот же кусок текста всегда
// одного цвета, и книга выглядит «разной» без единой картинки.
export const hue = i => (i * 47) % 360;

export const grad = i =>
  `linear-gradient(160deg,hsl(${hue(i)} 58% 30%),hsl(${(hue(i) + 50) % 360} 55% 13%))`;

// Бутафорские счётчики лайков/просмотров: детерминированы от индекса,
// чтобы не прыгали при каждом перерендере.
// У каждого счётчика есть НИЖНЯЯ граница, и это не украшательство: без неё
// самая первая карточка списка — та, которую видят раньше всех остальных, —
// показывала «0 комментариев, 0 репостов». Ролик с лайками и нулём всего
// остального читается как недоделанный экран, а не как ролик.
export const likes = i => (i * 37) % 900 + 12;
export const comments = i => (i * 11) % 90 + 4;
export const shares = i => (i * 7) % 60 + 2;
export const marks = i => (i * 53) % 4000 + 80;
export const views = i => (i * 91) % 900 + 3;

// Длительность «ролика» — та же бутафория, что и счётчики: от индекса, не от часов.
export const dur = i => ((i * 13) % 18 + 3) + ':' + String((i * 29) % 60).padStart(2, '0');

// Реакции в переписке. Живая переписка состоит не только из текста: между
// репликами всегда есть «ха-ха» и сердечки, и без них диалог выглядит
// служебной рассылкой, а не разговором.
//
// Как и всё остальное здесь — от индекса. Реакция, перескакивающая с одного
// сообщения на другое при прокрутке, хуже, чем её отсутствие.
const REACT = ['😂', '❤️', '🔥', '👍', '😅', '🥹'];
const REPLY = ['😂', '❤️', '🤣', '🥰'];

/** Значок реакции на пузыре i — или пусто. Примерно на каждом четвёртом. */
export const reaction = i => (i % 4 === 1 ? REACT[(i * 5) % REACT.length] : '');

/** Сколько человек поставили эту реакцию: 1–3, больше в личной переписке не бывает. */
export const reactionCount = i => (i * 7) % 3 + 1;

/** Ответ одним смайликом после пузыря i — или пусто. Примерно на каждом шестом. */
export const sticker = i => (i % 6 === 3 ? REPLY[(i * 3) % REPLY.length] : '');

/**
 * Смайлик под комментарием. Их тут заметно больше, чем реакций в переписке:
 * ветка комментариев без смайликов не бывает — это и есть половина того, зачем
 * их вообще открывают. Пусто у каждого третьего, чтобы ряд не выглядел
 * штампованным.
 */
export const commentEmo = i => (i % 3 === 2 ? '' : REACT[(i * 7) % REACT.length]);

/**
 * Заголовок «ролика» из куска книги.
 *
 * Раньше в списке стояли первые 70 знаков фрагмента — то есть обрывок посреди
 * фразы, часто с середины слова. Список из таких строк не читается как список
 * роликов, потому что у ролика есть название, а не начало текста.
 *
 * Берём первое предложение (но не короче 24 знаков — «Да.» заголовком не
 * бывает) и подрезаем по границе слова. Хвостовая запятая или тире убираются:
 * многоточие после них выглядит как опечатка.
 */
export function videoTitle(s, max = 64) {
  const t = String(s || '').replace(/\s+/g, ' ').trim();
  if (!t) return '';
  let out = t;
  const re = /[.!?…](?=\s|$)/g;
  let m;
  while ((m = re.exec(t))) {
    if (m.index >= 24) { out = t.slice(0, m.index); break; }
  }
  if (out.length > max) {
    const cut = out.lastIndexOf(' ', max);
    out = out.slice(0, cut > max / 2 ? cut : max).replace(/[\s,;:—–-]+$/, '') + '…';
  }
  return out;
}
